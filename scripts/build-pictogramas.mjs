// Puts the pictogram drawings inside the component bundle, so the Pictogram component and the entity pages draw with
// one and the same code: entidades/semilla.mjs and entidades/pictogramas.mjs, without their `import` and `export`
// words, go into artifact/project/components/bundle.js between /* @pictograms:start */ and /* @pictograms:end */ as
// the object PICTO. Run it after changing either file (npm run build does).
// Usage: node scripts/build-pictogramas.mjs [--check]   (--check changes nothing and fails if the bundle is out of date)
import { readFileSync, writeFileSync } from 'node:fs';

const BUNDLE = 'artifact/project/components/bundle.js', INICIO = '/* @pictograms:start */', FIN = '/* @pictograms:end */';
const read = (p) => readFileSync(p, 'utf8');
const fuente = ['entidades/semilla.mjs', 'entidades/pictogramas.mjs'].map((f) => read(f).replace(/^import .*$/gm, '').replace(/^export /gm, '').trim()).join('\n\n');
if (/<\/script|<!--/i.test(fuente)) throw new Error('El código de los pictogramas cerraría la etiqueta <script> de una página');

// What the bundle holds between its marks: the drawings in a scope of their own, and the three things the component uses.
function bloque() {
  return `${INICIO}\n  // Generated by scripts/build-pictogramas.mjs from entidades/semilla.mjs and entidades/pictogramas.mjs. Do not edit here.\n  var PICTO = (function () {\n${fuente}\n\n  return { dibujosDe: dibujosDe, trazosPictograma: trazosPictograma, PICTOGRAMAS: PICTOGRAMAS };\n  })();\n  ${FIN}`;
}

const bundle = read(BUNDLE), a = bundle.indexOf(INICIO), b = bundle.indexOf(FIN);
if (a < 0 || b < a) throw new Error(`${BUNDLE} no tiene las marcas ${INICIO} … ${FIN}`);
const nuevo = bundle.slice(0, a) + bloque() + bundle.slice(b + FIN.length);
if (process.argv.includes('--check')) {
  if (nuevo !== bundle) { console.error(`Pictogramas: ${BUNDLE} no está al día con entidades/. Corre: node scripts/build-pictogramas.mjs`); process.exit(1); }
  console.log('Pictogramas: el paquete está al día');
} else {
  if (nuevo !== bundle) writeFileSync(BUNDLE, nuevo);
  console.log(`Pictogramas: ${nuevo === bundle ? 'sin cambios' : 'paquete actualizado'} (${((bloque().length) / 1024) | 0} KB entre las marcas)`);
}
